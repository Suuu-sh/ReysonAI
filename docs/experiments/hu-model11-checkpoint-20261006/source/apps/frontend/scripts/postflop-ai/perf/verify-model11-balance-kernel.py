#!/usr/bin/env python3
"""Static exact correspondence, not a numerical test or acceptance proof."""
import hashlib
import json
from pathlib import Path


def digest(data):
    return hashlib.sha256(data).hexdigest()


def reconstruct(source, contract):
    if len(source) != contract['sourceBytes'] or digest(source) != contract['sourceSha256']:
        raise ValueError('Original balance source differs from the frozen source pin')
    text = source.decode('utf-8')
    if len(contract['substitutions']) != 5:
        raise ValueError('Exactly the five declared factory-only substitutions are allowed')
    for change in contract['substitutions']:
        if text.count(change['old']) != 1:
            raise ValueError('Factory substitution must match exactly once')
        text = text.replace(change['old'], change['new'])
    return (contract['header'] + text).encode('utf-8')


def verify(repository):
    contract_path = repository / 'apps/frontend/tests/fixtures/model11-balance-kernel-correspondence.json'
    contract_bytes = contract_path.read_bytes()
    contract = json.loads(contract_bytes)
    source = (repository / contract['source']).read_bytes()
    kernel = (repository / contract['kernel']).read_bytes()
    if reconstruct(source, contract) != kernel:
        raise ValueError('Kernel changed outside the exact allowed substitutions')
    if len(kernel) != contract['kernelBytes'] or digest(kernel) != contract['kernelSha256']:
        raise ValueError('Kernel differs from the pinned generated bytes')
    return {'kind': contract['kind'], 'sourceSha256': digest(source), 'kernelSha256': digest(kernel),
            'contractSha256': digest(contract_bytes), 'substitutions': len(contract['substitutions']),
            'result': 'exact-static-correspondence; not numerical proof'}


if __name__ == '__main__':
    repository = Path(__file__).resolve().parents[5]
    print(json.dumps(verify(repository), indent=2))
